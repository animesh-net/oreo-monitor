import importlib.util
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).parent.parent / "scripts"
sys.path.insert(0, str(SCRIPTS))
_spec = importlib.util.spec_from_file_location("clean_pr_body", SCRIPTS / "clean_pr_body.py")
clean_pr_body = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(clean_pr_body)
clean = clean_pr_body.clean

BODY = """## What changed

- Adds a check.

## Checklist

- [x] No `Co-Authored-By` or AI attribution in commits or this description
"""


def test_clean_body_is_unchanged():
    assert clean(BODY) == BODY


def test_generated_by_footer_and_its_rule_are_removed():
    body = BODY + "\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01ABC)_\n"
    assert clean(body) == BODY


def test_generated_with_footer_and_session_link_are_removed():
    body = (
        BODY + "\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n"
        "https://claude.ai/code/session_01ABC\n"
    )
    assert clean(body) == BODY


def test_requested_by_and_co_author_lines_are_removed():
    body = "Fix the check\n\nRequested by the AI agent\nCo-authored-by: Someone <a@b.c>\n"
    assert clean(body) == "Fix the check\n"


def test_windows_line_endings_are_handled():
    body = (
        BODY.replace("\n", "\r\n")
        + "\r\n---\r\n_Generated by [Claude Code](https://claude.ai/code)_"
    )
    assert clean(body) == BODY


def run(body):
    return subprocess.run(
        [sys.executable, str(SCRIPTS / "clean_pr_body.py")],
        input=body, capture_output=True, text=True, cwd=SCRIPTS,
    )  # fmt: skip


def test_script_exit_code_says_whether_it_changed_anything():
    assert run(BODY).returncode == 0
    changed = run(BODY + "\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n")
    assert changed.returncode == 1
    assert changed.stdout == BODY
